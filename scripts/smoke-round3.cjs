const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
(async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'anti-face-r3-ui-'));
  const env = { ...process.env, ANTI_FACE_TEST_USER_DATA: dir };
  delete env.ELECTRON_RUN_AS_NODE;
  delete env.ANTI_FACE_DEV_URL;
  let app;
  try {
    app = await electron.launch({ args: [path.join(root, 'tests/fixtures/desktop-two-windows.cjs')], cwd: root, env });
    const page = await app.firstWindow();
    await page.getByRole('button', { name: '连接与兼容', exact: true }).click();
    await page.getByText('Mock B', { exact: true }).click();
    await page.getByRole('heading', { name: '可以应用', exact: true }).waitFor();
    await page.getByRole('button', { name: '重新检测', exact: true }).click();
    await page.getByRole('button', { name: '应用到 Antigravity', exact: true }).click();
    await page.getByRole('heading', { name: '主题生效中', exact: true }).waitFor();
    assert.deepEqual(await app.evaluate(() => [global.round3Mock.windows.A.writes, global.round3Mock.windows.B.writes]), [0, 1]);
    await page.getByText('Mock A', { exact: true }).click();
    await page.getByRole('heading', { name: '可以应用', exact: true }).waitFor();
    assert.equal(await app.evaluate(() => !!global.round3Mock.windows.B.owner), true);
    await page.getByText('Mock B', { exact: true }).click();
    await page.getByRole('heading', { name: '主题生效中', exact: true }).waitFor();
    await page.getByRole('button', { name: '恢复原样', exact: true }).click();
    await page.getByRole('heading', { name: '可以应用', exact: true }).waitFor();
    assert.equal(await app.evaluate(() => global.round3Mock.windows.B.owner), null);
    // Delay B's response and switch back before it resolves.
    await page.getByText('Mock A', { exact: true }).click();
    await page.getByRole('heading', { name: '可以应用', exact: true }).waitFor();
    await app.evaluate(() => { global.round3Mock.delayB = 350; });
    await page.getByText('Mock B', { exact: true }).click();
    await page.getByText('Mock A', { exact: true }).click();
    await page.getByRole('heading', { name: '可以应用', exact: true }).waitFor();
    await page.getByRole('button', { name: '应用到 Antigravity', exact: true }).click();
    await page.getByRole('heading', { name: '主题生效中', exact: true }).waitFor();
    assert.deepEqual(await app.evaluate(() => [global.round3Mock.windows.A.writes, global.round3Mock.windows.B.writes]), [1, 1]);
    await page.getByRole('button', { name: '恢复原样', exact: true }).click();
    await app.evaluate(async () => { global.round3Mock.connected = false; await global.round3Mock.service.tick(); });
    await page.getByRole('heading', { name: '未连接', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: '应用到 Antigravity', exact: true }).isDisabled(), true);
    await app.evaluate(() => { global.round3Mock.connected = true; });
    await page.getByRole('button', { name: '重新检测', exact: true }).click();
    await page.getByRole('heading', { name: '可以应用', exact: true }).waitFor();
    await page.getByRole('button', { name: '实时任务状态', exact: true }).click();
    await page.getByLabel('选择宿主窗口').selectOption('A');
    const logDir = path.join(dir, 'synthetic-logs', 'brain/A/.system_generated/logs');
    await fs.mkdir(logDir, { recursive: true });
    await fs.writeFile(path.join(logDir, 'transcript.jsonl'), JSON.stringify({ type: 'USER_INPUT', created_at: '2020-01-01T00:00:00Z' }));
    const cache = path.join(dir, 'synthetic-logs', 'antigravity_stats_cache.json');
    await fs.writeFile(cache, JSON.stringify({ sessions: { A: { model: 'r3-model', input_tokens: 100, cached_tokens: 50, output_tokens: 200, duration_sec: 10 } } }));
    await app.evaluate(async () => { await global.round3Mock.telemetry.tick(); });
    await page.getByTitle('刷新状态').click();
    await page.getByText('33.3%', { exact: true }).waitFor();
    await fs.writeFile(cache, JSON.stringify({ sessions: { A: { model: 'r3-model' } } }));
    await app.evaluate(async () => { await global.round3Mock.telemetry.tick(); });
    await page.getByTitle('刷新状态').click();
    await page.getByText('不适用', { exact: true }).waitFor();
    assert.equal(await page.getByText('33.3%', { exact: true }).count(), 0);
    await fs.writeFile(cache, '{broken');
    await app.evaluate(async () => { await global.round3Mock.telemetry.tick(); });
    await page.getByTitle('刷新状态').click();
    await page.getByRole('status').filter({ hasText: '统计数据已过期或不可用' }).waitFor();
    console.log('PASS: real desktop IPC/UI selects, probes, applies and restores B; A isolation; rapid selection; idle disconnect/reconnect; missing/corrupt statistics display');
  } finally {
    if (app) await app.close();
    assert.ok(path.resolve(dir).startsWith(path.resolve(os.tmpdir()) + path.sep));
    await fs.rm(dir, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
